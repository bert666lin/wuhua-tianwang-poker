/**
 * AI 陪玩的显示名。
 *
 * 为什么要有这个文件：
 *   原来服务端给 AI 起名 `AI 1 / AI 2 / AI 3`，而匹配动画里飘的是前端
 *   写死的另一套中文名（老王/阿强/翠花）。结果玩家在匹配页看到"老王加入"，
 *   进牌桌却变成"AI 2"，两套名字对不上。
 *
 *   现在统一由服务端发名字，前端匹配页也用这份名单，牌桌与匹配页一致。
 *
 * 关于"要不要让 AI 看起来像真人"：
 *   名字用中文昵称是为了让牌桌不那么机械，但**不隐瞒身份** ——
 *   PlayerState.isAI 照常为 true，牌桌头像旁保留"电脑"标记，
 *   战绩里也会带「(AI)」后缀。让人误以为在跟真人打是欺骗，不做。
 */

/** 客气但不做作的中文昵称，尽量像本地牌友。 */
export const AI_NAMES: readonly string[] = [
  '老王', '阿强', '翠花', '大宝', '阿龙',
  '小梅', '老李', '阿凤', '细妹', '阿辉',
  '老陈', '阿珍',
];

/**
 * 按座位取一个稳定的名字。
 *
 * 同一房间内不重名：用座位号直接索引，座位数远小于名单长度。
 * 超出名单长度时退回带序号的名字（六人局也只用到 6 个，正常到不了）。
 */
export function aiNameForSeat(seatIndex: number): string {
  const name = AI_NAMES[seatIndex];
  return name ?? `电脑${seatIndex + 1}`;
}
